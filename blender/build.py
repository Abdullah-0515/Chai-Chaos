def brainrot_info():
    """Reads each brainrot's display name and rarity from src/shared/Brainrots.luau."""
    with open(BRAINROTS_LUAU, encoding="utf-8") as f:
        text = f.read()
    found = re.findall(r'id = "(\w+)", name = "([^"]+)", rarity = "(\w+)"', text)
    return {i: n for i, n, _ in found}, {i: r for i, _, r in found}


def fmt(n, places=3):
    text = f"{n:.{places}f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def vec(v, places=3):
    return "{" + ", ".join(fmt(x, places) for x in v) + "}"


def write_propdata(entries):
    materials = sorted({p["material"] for e in entries for p in e["parts"]})
    mat_index = {m: i + 1 for i, m in enumerate(materials)}
    lines = [
        "-- Every prop modelled in Blender, as Roblox parts. Props.luau builds them.",
        "--",
        "-- GENERATED by blender/build.py: do not edit by hand. Change the Python",
        "-- models in blender/ and run `python blender/build.py` again.",
        "--",
        "-- parts: { shape (B block, C cylinder, L ball), x, y, z, size x, y, z,",
        "--          rotation quaternion x, y, z, w, palette colour, material, flags }",
        "-- flags: 1 no collide, 2 always a part (never merged into the mesh),",
        "--        4 see-through, 8 gives off light, 16 no shadow, 32 parts version only,",
        "--        64 an eye (keeps its colour on mutated brainrots), 128 a vehicle's painted panel",
        "",
        "-- stylua: ignore start",
        "local PropData = {}",
        "",
        "PropData.palette = {",
    ]
    for name, (r, g, b) in kit.PALETTE:
        lines.append(f"\t{{ {r}, {g}, {b} }}, -- {name}")
    lines.append("}")
    lines.append("")
    lines.append("PropData.materials = { " + ", ".join(f'"{m}"' for m in materials) + " }")
    lines.append("")
    lines.append("PropData.props = {")
    for e in entries:
        lines.append(f"\t{e['name']} = {{")
        lines.append(f'\t\tcategory = "{e["category"]}",')
        lines.append(f"\t\tsize = {vec(e['size'])},")
        lines.append(f"\t\tcenter = {vec(e['center'])},")
        if e["mesh"]:
            m = e["mesh"]
            lines.append(f"\t\tmesh = {{ center = {vec(m['center'])}, size = {vec(m['size'])}, triangles = {m['triangles']} }},")
        if e["anchors"]:
            items = ", ".join(f"{k} = {vec(v)}" for k, v in sorted(e["anchors"].items()))
            lines.append(f"\t\tanchors = {{ {items} }},")
        lines.append("\t\tparts = {")
        for p in e["parts"]:
            values = (
                [f'"{p["shape"]}"']
                + [fmt(x) for x in p["pos"]]
                + [fmt(x) for x in p["size"]]
                + [fmt(x, 4) for x in p["quat"]]
                + [str(p["color"] + 1), str(mat_index[p["material"]]), str(p["flags"])]
            )
            lines.append("\t\t\t{ " + ", ".join(values) + " },")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("-- stylua: ignore end")
    lines.append("")
    lines.append("return PropData")
    with open(PROPDATA, "w") as f:
        f.write("\n".join(lines) + "\n")


def move(prop, offset):
    for obj in prop.pieces:
        obj.location += offset


def label(text, pos, size, coll):
    curve = bpy.data.curves.new(text, "FONT")
    curve.body = text
    curve.size = size
    curve.align_x = "CENTER"
    obj = bpy.data.objects.new("Label_" + text, curve)
    obj.location = pos
    obj.rotation_euler = (math.radians(70), 0, 0)
    mat = kit.special_material("black", False, False)
    curve.materials.append(mat)
    coll.objects.link(obj)
    return obj


def render_sheet(category, props, path):
    """Lays the props out in rows, renders them, then puts them back."""
    scene = bpy.context.scene
    gap = 6
    sizes = [(p, p.bounds_size) for p in props]
    widest = max(s[0] for _, s in sizes)
    row_width = max(widest, math.sqrt(sum((s[0] + gap) * (s[2] + gap) for _, s in sizes)) * 1.6)
    labels = bpy.data.collections.new("Labels_" + category)
    scene.collection.children.link(labels)
    x = y = 0.0
    row_depth = 0.0
    moved = []
    for prop, (sx, sy, sz) in sizes:
        if x > 0 and x + sx > row_width:
            x = 0.0
            y += row_depth + gap * 2
            row_depth = 0.0
        offset = Vector((x + sx / 2, y + sz / 2, 0))
        move(prop, offset)
        moved.append((prop, offset))
        label(prop.name, (offset.x, offset.y - sz / 2 - 1.5, 0.05), max(1.2, min(3.5, sx / 5)), labels)
        x += sx + gap
        row_depth = max(row_depth, sz)
    # an orthographic camera from the front, up high, fitted to everything
    from mathutils import Matrix

    corners = []
    for prop, _ in moved:
        for obj in prop.pieces:
            m = Matrix.Translation(obj.location) @ obj.rotation_quaternion.to_matrix().to_4x4()
            corners.extend(m @ v.co for v in obj.data.vertices)
    for obj in labels.objects:
        corners.append(obj.location.copy())
    lo = Vector((min(c.x for c in corners), min(c.y for c in corners), min(c.z for c in corners)))
    hi = Vector((max(c.x for c in corners), max(c.y for c in corners), max(c.z for c in corners)))
    center = (lo + hi) / 2
    cam_data = bpy.data.cameras.new("SheetCam")
    cam_data.type = "ORTHO"
    cam = bpy.data.objects.new("SheetCam", cam_data)
    scene.collection.objects.link(cam)
    view = Vector((0.35, -1.0, 0.85)).normalized()
    cam.location = center + view * (hi - lo).length * 2
    cam.rotation_euler = (-view).to_track_quat("-Z", "Y").to_euler()
    rot = cam.rotation_euler.to_matrix()
    right, up = rot.col[0], rot.col[1]
    xs = [(c - center).dot(right) for c in corners]
    ys = [(c - center).dot(up) for c in corners]
    aspect = 1600 / 1000
    width = max(xs) - min(xs)
    height = max(ys) - min(ys)
    cam_data.ortho_scale = max(width, height * aspect) * 1.06
    cam.location += right * (max(xs) + min(xs)) / 2 + up * (max(ys) + min(ys)) / 2
    cam_data.clip_end = 10000
    scene.camera = cam
    scene.render.resolution_x = 1600
    scene.render.resolution_y = 1000
    scene.render.image_settings.file_format = "JPEG"
    scene.render.image_settings.quality = 88
    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)

    bpy.data.objects.remove(cam)
    for obj in list(labels.objects):
        bpy.data.objects.remove(obj)
    bpy.data.collections.remove(labels)
    for prop, offset in moved:
        move(prop, -offset)


def render_grid(props, path, names, columns=4, size=(1600, 1000)):
    """Brainrot sheets: a tidy grid, seen from the front, with each one's name below it."""
    scene = bpy.context.scene
    cell = max(max(p.bounds_size[0], p.bounds_size[2]) for p in props) + 3.0
    columns = min(len(props), columns)
    rows = math.ceil(len(props) / columns)
    labels = bpy.data.collections.new("Labels_grid")
    scene.collection.children.link(labels)
    moved = []
    for i, prop in enumerate(props):
        col, row = i % columns, i // columns
        # the first row is at the back, so the sheet reads top to bottom
        offset = Vector(((col - (columns - 1) / 2) * cell, (rows - 1 - row) * cell * 2.0, 0))
        move(prop, offset)
        moved.append((prop, offset))
        text = names.get(prop.name, prop.name)
        lbl = label(text, (offset.x, offset.y - cell * 0.5, 0.05), 0.75, labels)
        lbl.rotation_euler = (math.radians(60), 0, 0)
    bpy.context.view_layer.update()
    corners = []
    for prop, _ in moved:
        for obj in prop.pieces:
            if obj.hide_render:
                continue
            corners.extend(obj.matrix_world @ v.co for v in obj.data.vertices)
    for obj in labels.objects:
        corners.extend(obj.matrix_world @ Vector(c) for c in obj.bound_box)
    lo = Vector((min(c.x for c in corners), min(c.y for c in corners), min(c.z for c in corners)))
    hi = Vector((max(c.x for c in corners), max(c.y for c in corners), max(c.z for c in corners)))
    center = (lo + hi) / 2
    cam_data = bpy.data.cameras.new("GridCam")
    cam_data.type = "ORTHO"
    cam = bpy.data.objects.new("GridCam", cam_data)
    scene.collection.objects.link(cam)
    view = Vector((0.15, -1.0, 0.65)).normalized()
    cam.location = center + view * 300
    cam.rotation_euler = (-view).to_track_quat("-Z", "Y").to_euler()
    rot = cam.rotation_euler.to_matrix()
    right, up = rot.col[0], rot.col[1]
    xs = [(c - center).dot(right) for c in corners]
    ys = [(c - center).dot(up) for c in corners]
    aspect = size[0] / size[1]
    cam_data.ortho_scale = max(max(xs) - min(xs), (max(ys) - min(ys)) * aspect) * 1.08
    cam.location += right * (max(xs) + min(xs)) / 2 + up * (max(ys) + min(ys)) / 2
    cam_data.clip_end = 1000
    scene.camera = cam
    scene.render.resolution_x = size[0]
    scene.render.resolution_y = size[1]
    scene.render.image_settings.file_format = "JPEG"
    scene.render.image_settings.quality = 88
    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)

    bpy.data.objects.remove(cam)
    for obj in list(labels.objects):
        bpy.data.objects.remove(obj)
    bpy.data.collections.remove(labels)
    for prop, offset in moved:
        move(prop, -offset)


def setup_render():
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 24
    scene.cycles.use_denoising = True
    scene.view_settings.view_transform = "Standard"
    world = bpy.data.worlds.new("Sky")
    if not world.node_tree:
        world.use_nodes = True
    bg = world.node_tree.nodes.get("Background")
    bg.inputs["Color"].default_value = (0.55, 0.75, 0.95, 1)
    bg.inputs["Strength"].default_value = 0.9
    scene.world = world
    sun_data = bpy.data.lights.new("Sun", "SUN")
    sun_data.energy = 3.2
    sun_data.angle = math.radians(8)
    sun = bpy.data.objects.new("Sun", sun_data)
    sun.rotation_euler = (math.radians(50), math.radians(10), math.radians(-35))
    scene.collection.objects.link(sun)
    ground_mesh = bpy.data.meshes.new("Ground")
    ground_mesh.from_pydata([(-2000, -2000, 0), (2000, -2000, 0), (2000, 2000, 0), (-2000, 2000, 0)], [], [(0, 1, 2, 3)])
    ground = bpy.data.objects.new("Ground", ground_mesh)
    ground.data.materials.append(kit.special_material("grass", False, False))
    scene.collection.objects.link(ground)
    return ground


def main():
    render = "--no-render" not in sys.argv
    only = None
    for arg in sys.argv[1:]:
        if arg.startswith("--only="):
            only = set(arg.split("=", 1)[1].split(","))
    os.makedirs(ASSETS, exist_ok=True)
    os.makedirs(DOCS, exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.context.preferences.filepaths.save_version = 0  # no .blend1 backups
    palette_path = os.path.join(ASSETS, "palette.png")
    kit.write_palette_png(palette_path)
    kit.Prop.palette_path = palette_path

    props = []
    entries = []
    names = set()
    for name, category, note, fn in kit.REGISTRY:
        assert name not in names, f"two props are called {name}"
        names.add(name)
        prop = kit.Prop(name, category, note)
        fn(prop)
        center, size = kit.bounds_roblox(prop)
        prop.bounds_size = (size[0], size[1], size[2])  # x, height, depth
        parts = [s for s in (kit.part_spec(o) for o in prop.pieces) if s]
        mesh = kit.joined_mesh(prop)
        mesh_info = None
        if mesh:
            obj, m_center, m_size, triangles = mesh
            assert triangles <= MAX_TRIANGLES, f"{name} has {triangles} triangles"
            mesh_info = {"center": m_center, "size": m_size, "triangles": triangles}
            prop.mesh_object = obj
        else:
            prop.mesh_object = None
        anchors = {k: tuple(kit.TO_ROBLOX @ v) for k, v in prop.anchors.items()}
        entries.append({
            "name": name, "category": category, "size": size, "center": center,
            "mesh": mesh_info, "anchors": anchors, "parts": parts,
        })
        props.append(prop)
        print(f"  {name:22s} {category:9s} {len(parts):4d} parts  {mesh_info['triangles'] if mesh_info else 0:6d} triangles")

    write_propdata(entries)
    print(f"wrote {PROPDATA}")

    # one FBX with every prop's mesh, side by side
    export = bpy.data.collections.new("ExportMeshes")
    bpy.context.scene.collection.children.link(export)
    x = 0.0
    for prop in props:
        if prop.mesh_object:
            export.objects.link(prop.mesh_object)
            prop.mesh_object.location = (x + prop.bounds_size[0] / 2, -400, 0)
            x += prop.bounds_size[0] + 8
    bpy.ops.object.select_all(action="DESELECT")
    for obj in export.objects:
        obj.select_set(True)
    fbx_path = os.path.join(ASSETS, "ChaiChaosProps.fbx")
    bpy.ops.export_scene.fbx(
        filepath=fbx_path,
        use_selection=True,
        object_types={"MESH"},
        axis_forward="Z",
        axis_up="Y",
        bake_space_transform=True,
        apply_unit_scale=True,
        apply_scale_options="FBX_SCALE_NONE",
        mesh_smooth_type="FACE",
        path_mode="COPY",
        embed_textures=True,
        use_mesh_modifiers=False,
    )
    print(f"wrote {fbx_path}")
    export.hide_render = True
    export.hide_viewport = True

    if render:
        ground = setup_render()
        names, rarities = brainrot_info()
        sheets = {}  # path -> props; brainrots get one sheet per rarity
        for prop in props:
            if only is not None and prop.category not in only:
                continue
            if prop.category == "brainrot":
                rarity = rarities.get(prop.name)
                assert rarity, f"{prop.name} is not in Brainrots.luau"
                path = os.path.join(BRAINROT_DOCS, f"{rarity.lower()}.jpg")
            else:
                path = os.path.join(DOCS, f"{prop.category}.jpg")
            sheets.setdefault(path, []).append(prop)
        os.makedirs(BRAINROT_DOCS, exist_ok=True)
        for path, group in sheets.items():
            # hide everything else while rendering this sheet
            showing = set(group)
            for prop in props:
                prop.coll.hide_render = prop not in showing
            if group[0].category == "brainrot":
                render_grid(group, path, names)
            else:
                render_sheet(os.path.basename(path), group, path)
            print(f"wrote {path}")
        for prop in props:
            prop.coll.hide_render = False
        bpy.data.objects.remove(ground)

    # lay everything out in a grid for the .blend file
    x = 0.0
    for prop in props:
        move(prop, Vector((x + prop.bounds_size[0] / 2, 0, 0)))
        x += prop.bounds_size[0] + 10
    blend_path = os.path.join(ASSETS, "ChaiChaosProps.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path, compress=True)
    print(f"wrote {blend_path}")

    import characters  # the brainrot character sheets in the README use the new sizes

    if characters.write_readme():
        print("updated the character sheets in README.md")


if __name__ == "__main__":
    main()
